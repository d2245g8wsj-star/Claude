"""
Runs the Nazaré model through the same measurement as the reference and
checks it against the calibration targets, plus the three things Nazaré does
on purpose that the reference does not (no aliasing, L/R spread, transient
memory). Writes CALIBRATION.md and exits non-zero if a check fails.

    python validate.py
"""
import json, math, os, sys
import numpy as np
import model as M
import fit as F
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "measure"))
import nzmeasure as nz

HERE = os.path.dirname(os.path.abspath(__file__))
TOL = {"thd_1k": 3.0, "thd_other": 8.0, "gain": 0.25, "fr": 0.25, "xt": 4.0}
ORDER = ("glass", "pipeline", "mavericks", "jaws", "teahupoo", "supertubes")


def row(R, f, L):
    return next(r for r in R["sines"] if r["freq"] == f and r["level"] == L)

def thd_db(r): return 20 * math.log10(max(r["ch"][0]["thd_pct"] / 100, 1e-9))

def fr_at(R, f, level=-18.0):
    e = next(e for e in R["response"] if e["level"] == level)
    i = min(range(len(e["f"])), key=lambda k: abs(e["f"][k] - f))
    return e["ch"][0]["mag_db"][i]

def aliasing(P, drive=18.0):
    """9973 Hz at 0 dBFS; level of the folded third harmonic at 48000 - 3*9973 = 18081 Hz."""
    n = M.FS; t = np.arange(n) / M.FS
    x = np.stack([np.sin(2 * np.pi * 9973 * t)] * 2)
    y = M.process(x, P, drive, noise=False, memory=0.0)[0, n // 4:]
    w = np.blackman(len(y)); s = np.abs(np.fft.rfft(y * w)); df = M.FS / len(y)
    pk = lambda f: s[int(round(f / df)) - 3: int(round(f / df)) + 4].max()
    return 20 * math.log10(pk(18081) / pk(9973))

def spread_check(P):
    sig, man = nz.build_signal()
    y = M.process(sig, P, 6.0, spread=1.0, channels=(7, 8), noise=False, memory=0.0)
    R = nz.analyse(y, sig.astype(np.float64), man)
    r = row(R, 1000.0, -6.0)
    return r["ch"][0]["gain_db"] - r["ch"][1]["gain_db"], r["ch"][0]["h_dbc"][0] - r["ch"][1]["h_dbc"][0]

def memory_check(P):
    """H2 after a -24 -> 0 -> -24 dBFS step: how far it swells, and whether it settles."""
    sig, man = nz.build_signal()
    seg = next(s for s in man["segments"] if s["kind"] == "step")
    x = sig[:, seg["start"]: seg["start"] + seg["length"]].astype(np.float64)
    def h2_track(mem):
        y = M.process(x, P, 6.0, noise=False, memory=mem)[0]
        win, hop = int(0.02 * M.FS), int(0.01 * M.FS); out = []
        for i in range(0, len(y) - win, hop):
            h = nz.harmonics(y[i:i + win], 1000.0, M.FS, 2); out.append(10 * math.log10(h[1] / h[0]))
        return np.array(out)
    a, b = h2_track(P.get("memory", 0.3)), h2_track(0.0)
    d = a - b  # the memory's contribution over time (10 ms steps)
    return float(d[100:130].max()), float(abs(d[180:192]).max())

def validate(key, P):
    T = F.targets(key)
    sig, man = nz.build_signal()
    checks = []
    for mode in ("channel", "bus"):
        y = M.process(sig, P, 6.0, mode=mode, memory=0.0 if mode == "channel" else None)
        R = nz.analyse(y, sig.astype(np.float64), man)
        if mode == "bus":
            xt = next(x for x in R["crosstalk"] if x["freq"] == 1000.0 and x["from"] == "L")["xtalk_db"]
            checks.append(("BUS crosstalk 1 kHz", F.XT[key][1], xt, TOL["xt"])); continue
        for L in (-18, -6, 0):
            checks.append((f"THD 1 kHz {L} dBFS", T[6.0][f"thd_1000_{L}"], thd_db(row(R, 1000.0, L)), TOL["thd_1k"]))
        for f in (100.0, 10000.0):
            checks.append((f"THD {int(f)} Hz -6 dBFS", T[6.0][f"thd_{int(f)}_-6"], thd_db(row(R, f, -6)), TOL["thd_other"]))
        checks.append(("gain 1 kHz -18 dBFS", T[6.0]["gain_1k_m18"], row(R, 1000.0, -18)["ch"][0]["gain_db"], TOL["gain"]))
        checks.append(("gain 1 kHz 0 dBFS", T[6.0]["gain_1k_0"], row(R, 1000.0, 0)["ch"][0]["gain_db"], TOL["gain"] * 2))
        for f in (20, 100, 5000, 20000):
            checks.append((f"response {f} Hz", T[6.0][f"fr{f}"], fr_at(R, f), TOL["fr"]))
        noise = max(R["noise_floor_dbfs_rms"])
    al = aliasing(P)
    dg, dh2 = spread_check(P)
    swell, settle = memory_check(P)
    own = [("aliasing, 9973 Hz 0 dBFS drive 18", "≤ −90 dB", al, al <= -90),
           ("L/R spread gain, channels 7/8", "≠ 0", dg, abs(dg) > 0.005),
           ("L/R spread H2, channels 7/8", "≠ 0", dh2, abs(dh2) > 0.2),
           ("memory: H2 swell after step", "≥ +0.5 dB" if P.get("memory", 0) >= 0.2 else "small", swell, swell >= 0.5 or P.get("memory", 0) < 0.2),
           ("memory: settled 0.8 s later", "≤ 0.5 dB", settle, settle <= 0.5),
           ("silence in, silence out", "< −140 dBFS", noise, noise < -140)]
    return checks, own

if __name__ == "__main__":
    models = M.load(); lines = []; failed = 0
    lines.append("# Nazaré calibration\n")
    lines.append("Generated by `dsp/validate.py`. The model runs through the same measurement as the reference "
                 "(`measure/nzmeasure.py`), at drive 6. Targets are the reference console each model is mapped to "
                 "(see `fit.py`); GLASS is Nazaré's own design and has no reference to match, only its own checks.\n")
    for key in ORDER:
        P = models[key]; checks, own = validate(key, P)
        ref = P.get("reference", {})
        src = "own design" if ref.get("designed") else f"reference {ref.get('plugin')} console {ref.get('console')}"
        lines.append(f"\n## {P['name']} ({P['desc']}, {src})\n")
        lines.append("| Check | Target | Nazaré | Δ | |\n|---|---|---|---|---|")
        for name, t, v, tol in checks:
            if key == "glass" and not name.startswith("response"):
                lines.append(f"| {name} | – | {v:.2f} | | |"); continue
            ok = abs(v - t) <= tol; failed += (not ok)
            lines.append(f"| {name} | {t:.2f} | {v:.2f} | {v - t:+.2f} | {'ok' if ok else 'off'} |")
        for name, t, v, ok in own:
            failed += (not ok)
            lines.append(f"| {name} | {t} | {v:.2f} | | {'ok' if ok else 'off'} |")
        print(key, "done", flush=True)
    open(os.path.join(HERE, "CALIBRATION.md"), "w").write("\n".join(lines) + "\n")
    print("checks off:", failed)
