"""
Writes the C++ data the plugin is built from, so the plugin and the Python
reference model can never disagree about a number:

  src/gen/Models.h     the six consoles (dsp/models.json) and, per console, the
                       drive table: knob position -> internal drive and the
                       auto gain that goes with it
  src/gen/Layout.h     every position on the panel (art/layout.json) and the
                       filmstrip geometry (docs/renders/strips.json)
  tests/vectors.h      shaper input/output pairs from dsp/model.py, which the
                       offline checks compare against the C++ shaper

    python tools/gen_cpp.py        (needs numpy and scipy)
"""
import json, math, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(ROOT, "dsp"))
import model as M   # noqa: E402
import fit as F     # noqa: E402

ORDER = ("glass", "pipeline", "mavericks", "jaws", "teahupoo", "supertubes")
THD_LO, THD_HI = -3.3, 1.4      # log10 of THD % across the drive knob, as on the concept page
TABLE = 129

def num(v): return repr(float(v)) if v is not None else "0.0"

def drive_table(P):
    """Knob position -> (drive dB, auto gain dB) for a 1 kHz tone at 0 VU (-18 dBFS)."""
    out = []
    for i in range(TABLE):
        t = i / (TABLE - 1)
        target = 20 * math.log10(10 ** (THD_LO + t * (THD_HI - THD_LO)) / 100)
        lo, hi = -140.0, 60.0
        for _ in range(48):
            mid = (lo + hi) / 2
            if F.metrics(P, 1000.0, -18, mid)["thd"] < target: lo = mid
            else: hi = mid
        d = (lo + hi) / 2
        out.append((d, -F.metrics(P, 1000.0, -18, d)["gain"]))
    return out

def models_h(models):
    L = ["#pragma once", "", "// Generated by tools/gen_cpp.py from dsp/models.json. Do not edit by hand.", "",
         "namespace nazare::gen", "{", "",
         "struct Model", "{",
         "    const char* name; const char* description;",
         "    bool pregain;",
         "    double k1, a2, a3, xover, tubeG, tubeB, preGain, makeup, clipC, clipP;",
         "    double lfF, lfG, hfF, hfG;                                   // pre-shelves (inverse after)",
         "    double hpF; int hpOrder; double lsF, lsG, pkF, pkG, pkQ, hsF, hsG, dcF;   // tone EQ",
         "    double gainDb, bump;",
         "    double xtFlat, xtLf, xtHf, xtLfF, xtHfF;                     // BUS crosstalk",
         "    double noiseDbfs, memory;",
         "};", "",
         f"inline constexpr int numModels = {len(ORDER)};",
         f"inline constexpr int driveTableSize = {TABLE};", "",
         "inline constexpr Model models[numModels] =", "{"]
    tables = []
    for k in ORDER:
        P = models[k]; s, p, e, x = P["shaper"], P["pre"], P["eq"], P["xtalk"]
        vals = [f'"{P["name"].replace(chr(0x2019), chr(39))}"', f'"{P["desc"]}"', "true" if P["drive_mode"] == "pregain" else "false",
                num(s["k1"]), num(s["a2"]), num(s["a3"]), num(s.get("xover", 0)), num(s.get("tube_g", 0)), num(s.get("tube_b", 0)),
                num(s.get("pre_gain", 1)), num(s.get("makeup", 1)), num(s["clip_c"]), num(s["clip_p"]),
                num(p["lf_f"]), num(p["lf_g"]), num(p["hf_f"]), num(p["hf_g"]),
                num(e.get("hp_f", 0)), str(int(e.get("hp_order", 1))), num(e.get("ls_f", 100)), num(e.get("ls_g", 0)),
                num(e.get("pk_f", 1000)), num(e.get("pk_g", 0)), num(e.get("pk_q", 0.8)), num(e.get("hs_f", 8000)), num(e.get("hs_g", 0)), num(e.get("dc_f", 3.0)),
                num(P["gain_db"]), num(P.get("bump", 0)),
                num(x["flat"]), num(x["lf"]), num(x["hf"]), num(x["lf_f"]), num(x["hf_f"]),
                num(P["noise_dbfs"]), num(P["memory"])]
        L.append("    { " + ", ".join(vals) + " },")
        tables.append(drive_table(P))
        print(k, "drive table", round(tables[-1][0][0], 1), "...", round(tables[-1][-1][0], 1), flush=True)
    L += ["};", "", "// Per console: drive in dB (6 = the calibration point) and auto gain in dB, at evenly spaced knob positions.",
          "inline constexpr double driveTable[numModels][driveTableSize][2] =", "{"]
    for tb in tables:
        L.append("    {" + ", ".join(f"{{ {d:.6f}, {g:.6f} }}" for d, g in tb) + "},")
    L += ["};", "", "} // namespace nazare::gen", ""]
    return "\n".join(L)

def layout_h():
    lay = json.load(open(os.path.join(ROOT, "art", "layout.json")))
    st = json.load(open(os.path.join(ROOT, "docs", "renders", "strips.json")))
    F_, R_ = lay["front"], lay["rear"]
    L = ["#pragma once", "", "// Generated by tools/gen_cpp.py from art/layout.json and docs/renders/strips.json.", "",
         "namespace nazare::layout", "{", "",
         f"inline constexpr int width = {lay['size'][0]}, height = {lay['size'][1]};",
         f"inline constexpr int imageScale = {int(st['scale'])};", "",
         "struct Point { float x, y; };", "struct Strip { float w, h; int n, cols, rows; };", ""]
    for key in ("drive", "small", "console", "trim", "toggle", "jewel"):
        m = st["strips"][key]
        L.append(f"inline constexpr Strip {key}Strip {{ {m['w']}f, {m['h']}f, {m['n']}, {m['cols']}, {m['rows']} }};")
    L.append("")
    for name, v in (("drive", F_["drive"]), ("spread", F_["spread"]), ("output", F_["output"]), ("console", F_["console"]),
                    ("jewel", F_["jewel"]), ("power", F_["power"])):
        L.append(f"inline constexpr Point {name} {{ {v['cx']}f, {v['cy']}f }};")
    L += [f"inline constexpr float driveDiameter = {F_['drive']['d']}f, smallDiameter = {F_['spread']['d']}f;",
          f"inline constexpr float consoleLabelRadius = {F_['console']['labelR']}f;",
          "inline constexpr float consoleAngles[6] = { " + ", ".join(f"{a}f" for a in F_["console"]["angles"]) + " };",
          f"inline constexpr Point vuCentre {{ {F_['vu']['cx']}f, {F_['vu']['cy']}f }};",
          f"inline constexpr float vuFaceW = {F_['vu']['face'][0]}f, vuFaceH = {F_['vu']['face'][1]}f;",
          f"inline constexpr Point vuPivot {{ {F_['vu']['pivot'][0]}f, {F_['vu']['pivot'][1]}f }};",
          f"inline constexpr float vuRadius = {F_['vu']['r']}f;",
          f"inline constexpr Point frontFlip {{ {F_['flip']['x']}f, {F_['flip']['y']}f }}, rearFlip {{ {R_['flip']['x']}f, {R_['flip']['y']}f }};", ""]
    for name in ("age", "noise", "os", "cal"):
        v = R_[name]; L.append(f"inline constexpr Point rear_{name} {{ {v['cx']}f, {v['cy']}f }};")
    L += [f"inline constexpr float trimDiameter = {R_['age']['d']}f;",
          "inline constexpr int stepFrames[4] = { " + ", ".join(str(x) for x in R_["os"]["frames"]) + " };",
          "inline constexpr float stepAngles[4] = { " + ", ".join(f"{a}f" for a in R_["os"]["angles"]) + " };"]
    for name in ("mode", "auto", "matched"):
        v = R_[name]; L.append(f"inline constexpr Point rear_{name} {{ {v['cx']}f, {v['cy']}f }};")
    c = R_["channel"]
    L += [f"inline constexpr Point rear_channel {{ {c['cx']}f, {c['cy']}f }};",
          f"inline constexpr float channelW = {c['w']}f, channelH = {c['h']}f;", "", "} // namespace nazare::layout", ""]
    return "\n".join(L)

def vectors_h(models):
    us = np.linspace(-1.5, 1.5, 41)
    L = ["#pragma once", "", "// Generated by tools/gen_cpp.py: dsp/model.py shaper() outputs, memory and spread off.", "",
         "namespace nazare::vectors", "{", "",
         "struct Case { int model; double drive; double in; double out; };", "",
         "inline constexpr Case cases[] =", "{"]
    for mi, k in enumerate(ORDER):
        for d in (-30.0, 0.0, 6.0, 18.0):
            ys = M.shaper(us, models[k], d)
            for u, y in zip(us, ys):
                L.append(f"    {{ {mi}, {d}, {float(u)!r}, {float(y)!r} }},")
    L += ["};", "", "// The reference model at the calibration point (drive 6, steady 1 kHz tone): THD and gain in dB.",
          "struct Level { int model; double level; double thdDb; double gainDb; };", "",
          "inline constexpr Level levels[] =", "{"]
    for mi, k in enumerate(ORDER):
        for lv in (-18, -6, 0):
            m = F.metrics(models[k], 1000.0, lv, 6.0)
            L.append(f"    {{ {mi}, {lv}.0, {m['thd']!r}, {m['gain']!r} }},")
    L += ["};", "", "} // namespace nazare::vectors", ""]
    return "\n".join(L)

if __name__ == "__main__":
    models = M.load()
    os.makedirs(os.path.join(ROOT, "src", "gen"), exist_ok=True)
    import re
    open(os.path.join(ROOT, "src", "gen", "Layout.h"), "w").write(re.sub(r"(?<![\w.])(-?\d+)f\b", r"\1.0f", layout_h()))
    open(os.path.join(ROOT, "tests", "vectors.h"), "w").write(vectors_h(models)) if os.path.isdir(os.path.join(ROOT, "tests")) else None
    open(os.path.join(ROOT, "src", "gen", "Models.h"), "w").write(models_h(models))
    print("wrote src/gen/Models.h, src/gen/Layout.h, tests/vectors.h")
